#!/usr/bin/env python3
"""
render-domain.py: render a domain JSON into the human-facing markdown.

The JSON is the source of truth. This script is the only thing allowed to write
domains/*.md, so the docs cannot drift from the data.

Usage: python3 scripts/render-domain.py D11 [D12 ...]
       python3 scripts/render-domain.py --all
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "domains"
OUT = ROOT / "domains"

ATOM_NAMES = {
    "A01": "interpreter confusion", "A02": "trust boundary crossing",
    "A03": "identity confusion", "A04": "state confusion",
    "A05": "type and shape confusion", "A06": "path and namespace confusion",
    "A07": "resource exhaustion", "A08": "information exposure",
    "A09": "cryptographic weakness", "A10": "logic assumption violation",
    "A11": "dependency compromise", "A12": "timing and ordering",
    "A13": "side channel", "A14": "human manipulation",
    "A15": "configuration divergence", "A16": "model and agent manipulation",
}

STAGE_NAMES = {
    "L01": "scope", "L02": "passive recon", "L03": "surface mapping", "L04": "discovery",
    "L05": "hypothesis", "L06": "probing", "L07": "exploitation", "L08": "proof",
    "L09": "escalation", "L10": "reporting", "L11": "fix verification", "L12": "monitoring",
}


def esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def render(d):
    L = []
    a = L.append
    a(f"# {d['id']}: {d['title']}")
    a("")
    a(f"Status: {d.get('status','')}  ")
    a(f"Generated: {d.get('generated','')} from `data/domains/{d['id']}.json`. Do not edit this file by hand.")
    a("")
    if d.get("why_this_domain_first"):
        a(f"> {d['why_this_domain_first']}")
        a("")

    # atoms
    a("## Atoms in this domain")
    a("")
    a("Every technique below is an instance of one of the 16 atoms in `docs/ATTACK-ONTOLOGY-v0.md`.")
    a("")
    a("| atom | name | how it shows up here |")
    a("|---|---|---|")
    for at in d.get("atoms", []):
        a(f"| {at} | {ATOM_NAMES.get(at,'')} | {esc(d.get('atom_notes',{}).get(at,''))} |")
    a("")

    # cells
    cells = d.get("required_cells", [])
    if cells:
        filled = sum(1 for c in cells if c.get("filled"))
        a("## Required cells and coverage")
        a("")
        a(f"`{filled}/{len(cells)}` required cells filled. Each cell is surface / lifecycle stage / agency level.")
        a("A cell is required only if a practitioner would want something there, and the reason is reviewable.")
        a("")
        a("| cell | filled | why it is required |")
        a("|---|---|---|")
        for c in cells:
            mark = "yes" if c.get("filled") else "**no**"
            a(f"| `{c['cell']}` | {mark} | {esc(c.get('why'))} |")
        a("")

    # entries
    entries = d.get("entries", [])
    a("## Entries")
    a("")
    a(f"{len(entries)} enriched entries. `driver` tells an agent how to invoke the thing, which is the field")
    a("every other list omits. `atom`, `preconditions` and `oracle` are what make a row testable.")
    a("")
    a("| name | stage | agency | atoms | driver | json | what it does |")
    a("|---|---|---|---|---|---|---|")
    for e in sorted(entries, key=lambda x: (x.get("stage", "L99"), x["id"])):
        drv = e.get("driver", {})
        ag = e.get("agency", "")
        a(f"| [{esc(e['name'])}]({e['url']}) | {e.get('stage','')} {STAGE_NAMES.get(e.get('stage',''),'')} "
          f"| {ag} | {','.join(e.get('atom',[]))} | `{esc(drv.get('install',''))}` "
          f"| {'yes' if drv.get('json') else 'no'} | {esc(e.get('role',''))} |")
    a("")

    # detail for entries that carry preconditions or notes
    rich = [e for e in entries if e.get("preconditions") or e.get("note")]
    if rich:
        a("### Details that matter")
        a("")
        for e in rich:
            a(f"**{e['name']}**  ")
            if e.get("preconditions"):
                a(f"- preconditions: {', '.join('`'+p+'`' for p in e['preconditions'])}")
            if e.get("oracle"):
                a(f"- oracle: {', '.join('`'+o+'`' for o in e['oracle'])}")
            if e.get("evades"):
                a(f"- defense levels it addresses: {', '.join(e['evades'])}")
            if e.get("detected_by"):
                a(f"- detected by: {', '.join(e['detected_by'])}")
            if e.get("note"):
                a(f"- note: {e['note']}")
            a("")

    # tree
    t = d.get("tree")
    if t:
        a("## Decision tree")
        a("")
        a("Machine readable at `trees/" + d["id"] + ".json`. This is the rendered view.")
        a("")
        out = []

        def walk(node, depth):
            pad = "  " * depth
            if node.get("q"):
                out.append(f"{pad}- **{node['q']}**")
                if node.get("why"):
                    out.append(f"{pad}  - _why:_ {node['why']}")
            for br in node.get("branches", []):
                out.append(f"{pad}- `{br['a']}`")
                if br.get("action"):
                    out.append(f"{pad}  - action: {br['action']}")
                    if br.get("tools"):
                        out.append(f"{pad}  - tools: {', '.join('`'+x+'`' for x in br['tools'])}")
                    if br.get("oracle"):
                        out.append(f"{pad}  - oracle: `{br['oracle']}`")
                if br.get("next"):
                    walk(br["next"], depth + 1)

        walk(t, 0)
        L.extend(out)
        a("")

    # mirror
    m = d.get("mirror", [])
    if m:
        a("## Defense mirror")
        a("")
        a("The other half of every row. An offensive entry with no matching detection and control is")
        a("incomplete, because the practical question is always against which defence.")
        a("")
        a("| attack | detect | control | rule |")
        a("|---|---|---|---|")
        for r in m:
            a(f"| {esc(r['attack'])} | {esc(r['detect'])} | {esc(r['control'])} | {esc(r['rule'])} |")
        a("")

    # gaps
    g = d.get("gaps", [])
    if g:
        a("## Gaps")
        a("")
        a("Recorded, not hidden. `no-tool` means nothing usable exists. `coverage` means a required cell is empty.")
        a("")
        a("| gap | class | build candidate |")
        a("|---|---|---|")
        for r in g:
            a(f"| {esc(r['gap'])} | {r['class']} | {esc(r.get('build_candidate',''))} |")
        a("")

    a("---")
    a("")
    a("_Counts in this file are rendered from the JSON and re-derived on every build. If a number here")
    a("disagrees with `data/domains/" + d["id"] + ".json`, the JSON is right._")
    return "\n".join(L) + "\n"


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return
    files = sorted(DATA.glob("D*.json")) if args == ["--all"] else [DATA / f"{a}.json" for a in args]
    OUT.mkdir(exist_ok=True)
    for f in files:
        if not f.exists():
            print(f"missing {f}")
            continue
        d = json.load(open(f))
        slug = d["title"].split(":")[0].strip().lower().replace(" ", "-")
        target = OUT / f"{d['id']}-{slug}.md"
        target.write_text(render(d))
        tdir = ROOT / "trees"
        tdir.mkdir(exist_ok=True)
        if d.get("tree"):
            json.dump(d["tree"], open(tdir / f"{d['id']}.json", "w"), indent=1)
        print(f"rendered {target.relative_to(ROOT)} ({len(d.get('entries',[]))} entries)")


if __name__ == "__main__":
    main()
