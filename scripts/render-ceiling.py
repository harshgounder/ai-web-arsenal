#!/usr/bin/env python3
"""
render-ceiling.py: generate docs/CEILING.md from the gap classification.

The report is generated for the same reason every other document here is: a number typed by hand is a
number that will drift. This reads data/gap/SUMMARY.json and data/gap/classification.jsonl and writes
the file.

Run: python3 scripts/render-ceiling.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAP = ROOT / "data" / "gap"
OUT = ROOT / "docs" / "CEILING.md"

LENS_NAMES = {
    "L01": "substrate", "L02": "network and transport", "L03": "protocol semantics",
    "L04": "frameworks and runtimes", "L05": "client and browser", "L06": "identity and session",
    "L07": "data and storage", "L08": "business logic and money", "L09": "infrastructure and edge",
    "L10": "supply chain", "L11": "human and organisational", "L12": "AI and agentic systems",
    "L13": "regulation and standards", "L14": "evidence and oracle science",
    "L15": "detection and defence industry", "L16": "history and corpus",
}


def main():
    s = json.loads((GAP / "SUMMARY.json").read_text(encoding="utf-8"))
    rows = [json.loads(l) for l in (GAP / "classification.jsonl").read_text(encoding="utf-8").splitlines()
            if l.strip()]
    cov = [json.loads(l) for l in (ROOT / "data" / "coverage" / "coverage.jsonl")
           .read_text(encoding="utf-8").splitlines() if l.strip()]

    observed = sum(1 for r in cov if r["level"] == "L3")
    total = s["factors_total"]
    covered = s["covered_l2_plus"]
    gap = s["gap_total"]
    c1, c2, c3 = (s["reachable_by_authoring"], s["reachable_by_lab"], s["unavailable"])

    per = {}
    for r in rows:
        per.setdefault(r["lens"], {"I": 0, "II": 0, "III": 0})[r["class"]] += 1
    cov_by = {}
    for r in cov:
        if r["level"] in ("L2", "L3"):
            cov_by[r["lens"]] = cov_by.get(r["lens"], 0) + 1

    lines = []
    A = lines.append
    A("# The ceiling")
    A("")
    A("Generated by `scripts/render-ceiling.py` from `data/gap/`. Do not edit by hand.")
    A("")
    A(f"Set D is {total:,} factors. {covered} are covered at L2 or better, so the gap is {gap:,}. "
      "This document classifies that gap, because a gap you cannot act on is just a number that makes "
      "you feel bad.")
    A("")
    A("## The three classes")
    A("")
    A("| class | meaning | cost | factors |")
    A("|---|---|---|---|")
    A(f"| I | derivable with noise. The mechanism is published, so it can be written from what exists. "
      f"The error is the author's misreading. | authoring | **{c1}** |")
    A(f"| II | inferable from structure. A property of a running system, visible only under a probe. "
      f"| a lab and a target | **{c2}** |")
    A(f"| III | genuinely unavailable. A fact about one organisation's internals, or unpublished "
      f"research. No defensible proxy. | impossible from outside | **{c3}** |")
    A("")
    A(f"**The ceiling is {s['ceiling_pct']} percent.** That is the share of Set D any collection could "
      "reach from outside, given unlimited authoring and lab time. It is not a forecast of what this "
      "repo will reach, and it is not a promise.")
    A("")
    A("The ceiling is high, and that is the most important finding in this document. Almost nothing in "
      "the denominator is hidden. The constraint on completeness here is effort and access to a lab, "
      "not secrecy. Fifty one factors are permanently out of reach and most of them are about how a "
      "particular company runs itself, which no external party can know.")
    A("")
    A("## Where the gap sits")
    A("")
    A("| lens | covered | class I | class II | class III |")
    A("|---|---|---|---|---|")
    for lens in sorted(per):
        v = per[lens]
        A(f"| {lens} {LENS_NAMES.get(lens, '')} | {cov_by.get(lens, 0)} | {v['I']} | {v['II']} | {v['III']} |")
    A(f"| **total** | **{covered}** | **{c1}** | **{c2}** | **{c3}** |")
    A("")
    A("Read it by column, not by row.")
    A("")
    A(f"- **Class I is {c1} factors.** This is the cheapest coverage in the whole project: no target, "
      "no lab, no permission. Write the entry with a procedure and an oracle and it moves. L13 promises "
      "the most here, because statute and standards are published and this repo simply has not written "
      "them down.")
    A(f"- **Class II is {c2} factors, and it is the real project.** Nearly every lens is dominated by "
      "it. It is also where the current zero lives: nothing is observed because no lab exists, and two "
      "thirds of the gap can only be closed with one.")
    A(f"- **Class III is {c3} factors.** Seventeen of them are organisational. The honest statement is "
      "that a public repo cannot answer them, and any collection claiming to has invented an answer.")
    A("")
    A("## What closing each class takes")
    A("")
    A("Effort in the table below is a ESTIMATE, not a measurement, and it is labelled that way on "
      "purpose. It assumes one authored entry with procedure, oracle and counter per Class I factor, "
      "and one lab per group of related Class II factors rather than one per factor.")
    A("")
    A("| to close | work | ESTIMATE |")
    A("|---|---|---|")
    A(f"| all of class I | {c1} authored entries | 30 to 45 hours |")
    A(f"| a first lab batch | 6 labs covering the highest value class II groups | 20 to 30 hours |")
    A(f"| all of class II | about 60 labs across 16 lenses | 300 to 500 hours |")
    A(f"| class III | nothing | not possible |")
    A("")
    A("## What the ceiling means for the claim")
    A("")
    A("Three statements are now defensible, and they are ranked by strength.")
    A("")
    A(f"1. **This repo covers {round(100.0 * covered / total, 1)} percent of a published denominator of "
      f"{total:,} factors.** Checkable by anyone who reads `data/denominator/` and "
      "`data/coverage/coverage.jsonl` and disagrees with a grade.")
    A(f"2. **{round(100.0 * covered / total, 1)} percent today, {round(100.0 * (covered + c1) / total, 1)} "
      f"percent if every Class I factor were authored, {s['ceiling_pct']} percent at the ceiling.** The "
      "middle number is the one an author can reach alone.")
    A("3. **A public collection cannot exceed the ceiling**, because "
      f"{c3} factors depend on facts no outsider can obtain.")
    A("")
    A("What is not defensible, and will not be written in the README: that this is complete, that it "
      "covers everything, or that the number is high. It is a fraction with a denominator, and the "
      "denominator is the contribution.")
    A("")
    A("## The one number still at zero")
    A("")
    A(f"Observed coverage is {observed} of {total}. Every other figure in this repo is an argument; "
      "that one is an absence, and it closes only with a lab.")
    A("")
    A(f"{observed} factors are observed, from four labs that all ran on 2026-10-27:")
    A("")
    A("| lab | what it shows | control |")
    A("|---|---|---|")
    A("| lab-01-race | 24 parallel creates produced 23 duplicates | sequential creates produced one |")
    A("| lab-02-jwt-alg | an unsigned token with alg none reached admin | wrong signature 401, user token 403 |")
    A("| lab-03-route-order | /%61dmin and /ADMIN reached admin | plain path 401, valid key accepted |")
    A("| lab-04-cache-poison | a hostile header was served to another client | reflection is header dependent, no-store honoured |")
    A("")
    A("Every record is in `data/observations/observations.jsonl` and replays with "
      "`python3 scripts/observe.py --verify`.")
    A("")
    A(f"The remaining {total - observed} factors are still read and cited. `ESTABLISHED` means cited, "
      "never executed, and that distinction stays in the README badge until a lab changes it.")
    A("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
