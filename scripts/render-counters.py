#!/usr/bin/env python3
"""
render-counters.py: generate counters/COUNTERS.md from data/counters/classes.json.

The counter layer is the defensive half of this repo, and its value depends on one thing being stated
plainly for every class: what the control structurally cannot see. `sees` and `blind_spot` are adjacent in
the data on purpose, because a control described only by what it stops is marketing.

The class ids match the companion atlas, so a pattern's `counter` field and a class record here refer to
the same thing. The generator refuses to emit a class whose atom references do not exist in the atlas.

Run:
  python3 scripts/render-counters.py           render
  python3 scripts/render-counters.py --check    validate only
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "counters" / "classes.json"
OUT = ROOT / "counters" / "COUNTERS.md"
ATLAS = ROOT.parent / "web-attack-atlas"


def atoms():
    p = ATLAS / "data" / "atoms.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text(encoding="utf-8"))
    return {a["id"]: a.get("name", "") for a in d.get("atoms", d if isinstance(d, list) else [])}


def render(doc, atom_names):
    L = []
    a = L.append
    a("# Counters by control class")
    a("")
    a("Generated by `scripts/render-counters.py` from `data/counters/classes.json`. Do not edit by hand.")
    a("")
    a("A defender reads this to find the gap in their own control. A researcher reads it the other way:")
    a("the blind spot column is the whole attack surface of that control, and the cost column is what")
    a("exploiting it will cost you.")
    a("")
    a("The classes are the same ids the companion atlas uses, so a pattern's `counter` field and a")
    a("record here refer to the same thing.")
    a("")
    a("| class | control | atoms it touches |")
    a("|---|---|---|")
    for c in doc["classes"]:
        ats = ", ".join(c.get("atoms") or []) or "-"
        a(f"| {c['id']} | {c['name']} | {ats} |")
    a("")
    for c in doc["classes"]:
        a(f"## {c['id']} {c['name']}")
        a("")
        a(f"**Mechanism.** {c['mechanism']}")
        a("")
        a(f"**What it sees.** {c['sees']}")
        a("")
        a(f"**What it structurally cannot see.** {c['blind_spot']}")
        a("")
        a(f"**The bypass.** {c['bypass']}")
        a("")
        a(f"**What that costs.** {c['cost']}")
        a("")
        a(f"**The rule that would catch it.** {c['detection']}")
        a("")
        if c.get("atoms"):
            named = [f"{x} {atom_names.get(x, '')}".strip() for x in c["atoms"]]
            a(f"**Atoms.** {', '.join(named)}")
            a("")
    a("---")
    a("")
    a("Read the blind spot column as a list of preconditions. Every one of them is a statement about")
    a("what the control assumes, and assumptions are where the work is.")
    a("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    doc = json.loads(SRC.read_text(encoding="utf-8"))
    names = atoms()
    problems = []

    ids = [c["id"] for c in doc["classes"]]
    if len(ids) != len(set(ids)):
        problems.append("duplicate class id")
    for c in doc["classes"]:
        for field in ("mechanism", "sees", "blind_spot", "bypass", "cost", "detection"):
            if not c.get(field):
                problems.append(f"{c['id']}: empty {field}")
        if names is not None:
            for at in c.get("atoms") or []:
                if at not in names:
                    problems.append(f"{c['id']}: cites atom {at}, which the atlas does not define")

    if problems:
        print(f"{len(problems)} problem(s):", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1

    if args.check:
        print(f"{len(doc['classes'])} control classes checked, every field present"
              f"{'' if names is not None else ', atom references unchecked (atlas not found)'}")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(doc, names or {}), encoding="utf-8")
    print(f"rendered {len(doc['classes'])} classes into {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
