#!/usr/bin/env python3
"""
gen-bootstrap.py: generate bootstrap scripts from data/install-matrix.json.

The matrix is the only place a package name lives. This script renders it into shell.
Regenerate after any manifest change; never hand-edit the output.

Outputs:
  bootstrap/lib.sh
  bootstrap/00-prereqs.sh
  bootstrap/10-install-<profile>.sh   (one per profile that has tools)
  bootstrap/90-verify.sh
"""
import json, os, re, stat
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
M = json.load(open(ROOT / "data" / "install-matrix.json"))
TOOLS = M["tools"]
BOOT = ROOT / "bootstrap"
BOOT.mkdir(exist_ok=True)

HEADER = """#!/usr/bin/env bash
# GENERATED by scripts/gen-bootstrap.py from data/install-matrix.json
# Do not edit by hand. Regenerate instead.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
. "$HERE/lib.sh"
"""

LIB = r"""#!/usr/bin/env bash
# lib.sh: shared helpers. Sourced by every generated script.
# Design rules:
#   - never run as root, refuse early
#   - never pipe curl to sh
#   - every install is idempotent (skip when already present)
#   - --dry-run prints what would happen and changes nothing
#   - everything is logged to bootstrap/logs/<script>-<timestamp>.log

DRY=${DRY:-0}
LOG_DIR="$HERE/logs"
mkdir -p "$LOG_DIR"
LOG="$LOG_DIR/$(basename "${BASH_SOURCE[1]:-bootstrap}")-$(date +%Y%m%d-%H%M%S).log"

c_reset=$'\033[0m'; c_ok=$'\033[32m'; c_warn=$'\033[33m'; c_err=$'\033[31m'; c_dim=$'\033[2m'

log()  { printf '%s\n' "$*" | tee -a "$LOG" >/dev/null; printf '%s\n' "$*"; }
ok()   { printf '%s  ok  %s%s\n' "$c_ok" "$*" "$c_reset"; log "OK   $*"; }
warn() { printf '%s warn %s%s\n' "$c_warn" "$*" "$c_reset"; log "WARN $*"; }
err()  { printf '%s fail %s%s\n' "$c_err" "$*" "$c_reset"; log "FAIL $*"; }

require_user() {
  if [ "$(id -u)" -eq 0 ]; then
    err "do not run this as root. run as your normal user; the script asks for sudo when needed."
    exit 1
  fi
}

require_arch() {
  if ! command -v pacman >/dev/null 2>&1; then
    err "pacman not found. this bootstrap is Arch first (Arch, CachyOS, EndeavourOS, Manjaro)."
    err "on another distro read docs/INSTALL-OTHER.md, which lists the same tools per channel."
    exit 1
  fi
}

aur_helper() {
  for h in paru yay pikaur; do
    if command -v "$h" >/dev/null 2>&1; then printf '%s' "$h"; return 0; fi
  done
  printf ''
}

have() { command -v "$1" >/dev/null 2>&1; }

run() {
  if [ "$DRY" = "1" ]; then
    printf '%s[dry-run] %s%s\n' "$c_dim" "$*" "$c_reset"
    log "DRY  $*"
    return 0
  fi
  log "RUN  $*"
  "$@"
}

p_pacman() {
  local pkg="$1"
  if pacman -Qi "$pkg" >/dev/null 2>&1; then ok "pacman: $pkg already installed"; return 0; fi
  run sudo pacman -S --needed --noconfirm "$pkg" || { err "pacman failed: $pkg"; return 1; }
  ok "pacman: $pkg"
}

p_aur() {
  local pkg="$1" helper
  helper="$(aur_helper)"
  if [ -z "$helper" ]; then
    err "no AUR helper (paru/yay/pikaur). install one first: sudo pacman -S --needed base-devel git; then build paru from AUR."
    return 1
  fi
  if pacman -Qi "${pkg%-bin}" >/dev/null 2>&1 || pacman -Qi "$pkg" >/dev/null 2>&1; then
    ok "aur: $pkg already installed"; return 0
  fi
  run "$helper" -S --needed --noconfirm "$pkg" || { err "aur failed: $pkg"; return 1; }
  ok "aur: $pkg"
}

p_pipx() {
  local pkg="$1"
  have pipx || { err "pipx missing, run 00-prereqs.sh first"; return 1; }
  if pipx list --short 2>/dev/null | grep -q "^${pkg} "; then ok "pipx: $pkg already installed"; return 0; fi
  run pipx install "$pkg" || { err "pipx failed: $pkg"; return 1; }
  ok "pipx: $pkg"
}

p_git() {
  local url="$1" dest="${2:-}"
  if [ -z "$dest" ]; then dest="$HOME/$(basename "$url" .git)"; fi
  if [ -d "$dest/.git" ]; then
    ok "git: $dest present"; return 0
  fi
  run git clone --depth 1 "$url" "$dest" || { err "clone failed: $url"; return 1; }
  ok "git: $url -> $dest"
}

summary() {
  local failed="${1:-0}"
  echo
  if [ "$failed" -eq 0 ]; then ok "done. log: $LOG"; else warn "$failed step(s) failed. log: $LOG"; fi
  printf '%snext: bash bootstrap/90-verify.sh%s\n' "$c_dim" "$c_reset"
}
"""

PREREQ = HEADER + r'''
# 00-prereqs.sh: the things every profile assumes.
require_user
require_arch

log "ai-web-arsenal bootstrap: prerequisites"
log "log file: $LOG"

# base-devel and git are needed to build anything from the AUR.
install_core() {
  local core=(base-devel git curl)
  local missing=()
  for p in "${core[@]}"; do pacman -Qi "$p" >/dev/null 2>&1 || missing+=("$p"); done
  if [ ${#missing[@]} -gt 0 ]; then
    run sudo pacman -S --needed --noconfirm "${missing[@]}" || return 1
  fi
  ok "core packages present"
}

install_core || { err "core install failed"; exit 1; }

if [ -z "$(aur_helper)" ]; then
  warn "no AUR helper found. installing paru as the default."
  if [ "$DRY" = "1" ]; then
    printf '%s[dry-run] git clone paru && makepkg -si%s\n' "$c_dim" "$c_reset"
  else
    sudo pacman -S --needed --noconfirm base-devel git
    tmp="$(mktemp -d)"
    git clone --depth 1 https://aur.archlinux.org/paru.git "$tmp/paru"
    ( cd "$tmp/paru" && makepkg -si --noconfirm ) || warn "paru build failed, install yay manually"
    rm -rf "$tmp"
  fi
fi
ok "AUR helper: $(aur_helper)"

# uv is the python install engine, and it comes from the official repos.
pacman -Qi uv >/dev/null 2>&1 || run sudo pacman -S --needed --noconfirm uv
ok "uv: $(command -v uv || echo missing)"

summary 0
'''

VERIFY = HEADER + r'''
# 90-verify.sh: does every bin actually run.
require_user
log "verifying installed tools"
fail=0; n=0; miss=0
while IFS=$'\t' read -r id bin cmd; do
  [ -z "$id" ] && continue
  n=$((n+1))
  if [ -z "$bin" ] || [ "$bin" = "-" ]; then
    ok "$id (corpus, no binary)"
    continue
  fi
  if ! have "$bin"; then
    warn "$id: binary '$bin' not on PATH (not installed, or not in this profile)"
    miss=$((miss+1)); continue
  fi
  if eval "$cmd" >/dev/null 2>&1; then
    ok "$id: $cmd"
  else
    warn "$id: present but '$cmd' failed"
    fail=$((fail+1))
  fi
done < <(python3 - <<'PY'
import json, pathlib
m = json.load(open(pathlib.Path("data/install-matrix.json")))
for t in m["tools"]:
    print("\t".join([t["id"], t["bin"] or "-", t.get("verify") or t.get("verify_cmd") or "true"]))
PY
)
echo
ok "checked $n, missing $miss, failed $fail"
[ "$fail" -eq 0 ] || exit 1
'''

# verify commands live in tools.yaml, not the matrix. read them directly.
import yaml
Y = {t["id"]: t for t in yaml.safe_load(open(ROOT / "manifest" / "tools.yaml"))["tools"]}


def render_profile(profile, tools):
    body = [HEADER]
    body.append(f'log "profile: {profile}"')
    body.append("require_user")
    body.append("require_arch")
    body.append("")
    body.append("FAILED=0")
    body.append("")
    for t in tools:
        res = t["resolved"] or {}
        ch, pkg = res.get("channel"), res.get("pkg")
        if not ch:
            body.append(f'warn "{t["id"]}: unresolved in the matrix, skipped"')
            continue
        body.append(f'log "--- {t["id"]}: {t.get("role","")}"')
        if t["installed"]:
            body.append(f'ok "{t["id"]} already present"')
            continue
        if ch == "pacman":
            body.append(f'p_pacman {shell_quote(pkg)} || FAILED=$((FAILED+1))')
        elif ch == "aur":
            body.append(f'p_aur {shell_quote(pkg)} || FAILED=$((FAILED+1))')
        elif ch == "pipx":
            body.append(f'p_pipx {shell_quote(pkg)} || FAILED=$((FAILED+1))')
        elif ch == "git":
            dest = "$HOME/nuclei-templates" if t["id"] == "nuclei-templates" else ""
            body.append(f'p_git {shell_quote(pkg)} {shell_quote(dest) if dest else ""} || FAILED=$((FAILED+1))')
        else:
            body.append(f'warn "{t["id"]}: channel {ch} not scripted, see manifest"')
        body.append("")
    body.append("summary \"$FAILED\"")
    return "\n".join(body) + "\n"


import shlex


def shell_quote(s):
    return shlex.quote(s) if s else '""'


def main():
    (BOOT / "lib.sh").write_text(LIB)
    (BOOT / "00-prereqs.sh").write_text(PREREQ)
    (BOOT / "90-verify.sh").write_text(VERIFY)

    profiles = {}
    for t in TOOLS:
        for p in t.get("profiles", []):
            profiles.setdefault(p, []).append(t)

    order = ["minimal", "recon", "web", "api", "ai-agent", "mobile", "re", "all"]
    made = []
    written = {"lib.sh", "00-prereqs.sh", "90-verify.sh"}
    for i, p in enumerate([x for x in order if x in profiles], start=1):
        # 'all' is the union, so it is rendered last as the sum of everything
        tools = profiles[p]
        path = BOOT / f"{10 + i * 5:02d}-install-{p}.sh"
        path.write_text(render_profile(p, tools))
        made.append((p, path.name, len(tools)))
        written.add(path.name)

    # This directory is generated. A leftover from an earlier numbering is a trap: `bash
    # bootstrap/*.sh` would run it, and the count of scripts stops matching the count claimed.
    # Three such orphans existed (35-install-mobile, 40-install-re, 45-install-all).
    removed = []
    for f in sorted(BOOT.glob("*.sh")):
        if f.name not in written and re.match(r"^\d{2}-.*\.sh$", f.name):
            f.unlink()
            removed.append(f.name)

    for f in list(BOOT.glob("*.sh")):
        f.chmod(f.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    print(f"{'profile':12s} {'script':32s} tools")
    for p, name, n in made:
        print(f"{p:12s} {name:32s} {n}")
    if removed:
        print(f"\nremoved {len(removed)} orphaned script(s): {', '.join(removed)}")
    print(f"\nwrote {len(written)} scripts into bootstrap/")


if __name__ == "__main__":
    main()
